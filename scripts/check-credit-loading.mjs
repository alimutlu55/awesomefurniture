// Held requests verify the wallet without creating payments or spending real credits.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const base = process.env.LOADING_TEST_URL ?? 'http://127.0.0.1:5177';
const output = process.argv[2];
if (output) await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  for (const width of [320, 390, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    const errors = [], requests = [], waiting = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/credits**', route => { if (waiting.length) waiting.shift()(route); else requests.push(route); });
    const take = () => requests.length ? Promise.resolve(requests.shift()) : new Promise(resolve => waiting.push(resolve));
    const respond = async json => (await take()).fulfill({ json });
    const shot = async name => { if (output) await page.screenshot({ path: `${output}/${name}-${width}.png` }); };
    await page.route('**/credit-loading-review*', route => route.fulfill({ contentType: 'text/html', body: `
      <body style="margin:0;background:#e9e5df"><div id="host"></div><script type="module">
      import {bindCreditWallet} from '/src/presentation/credits/credit-wallet.ts';
      import {createEditorLifetime} from '/src/presentation/viewport/editor-lifetime.js';
      import {CREDIT_PACKS,CREDIT_FEATURES,packCredits,packSaving} from '/src/domain/credits/credit-catalog.ts';
      import css from '/src/presentation/credits/credits.css?raw';
      import loadingCss from '/src/presentation/components/loading-state.css?raw';
      const host=document.querySelector('#host'),shadow=host.attachShadow({mode:'open'});
      shadow.innerHTML='<style>:host{font:14px system-ui;container-type:inline-size;display:block;min-height:100vh;--panel:#faf8f3;--ink:#302d26;--line:#dfd9ce}'+css+loadingCss+'</style><div id="app"><div id="menu"><div class="dd-title">Menu</div></div></div>';
      window.review={redirects:[],payload:{balance:50,account:{anonymous:false,email:'test@example.com',required:false},features:CREDIT_FEATURES.map(f=>({...f,freeLeft:0})),packs:CREDIT_PACKS.map(p=>({...p,price:p.prices.pln,currency:'pln',featured:!!p.featured,intro:!!p.intro,total:packCredits(p),saving:packSaving(p,'pln')})),history:[],passes:[],providers:[]}};
      review.wallet=bindCreditWallet({dom:{host,$:s=>shadow.querySelector(s)},lifetime:createEditorLifetime(),platform:{accessToken:async()=>null,designId:()=>null,returned:()=>location.search?{outcome:'success',orderId:'00000000-0000-4000-8000-000000000001'}:null,redirect:url=>review.redirects.push(url)},toast:()=>{},signIn:()=>{}});
      </script></body>` }));
    await page.goto(base + '/credit-loading-review');
    const chip = page.locator('.cr-chip'), sheet = page.locator('.cr-sheet').first();
    await chip.waitFor();
    assert.equal(await chip.isDisabled(), true);
    assert.equal(await chip.getAttribute('aria-busy'), 'true');
    const payload = await page.evaluate(() => review.payload);
    await respond(payload);
    await page.getByRole('menuitem', { name: 'Credits: 50. Open your wallet', exact: true }).waitFor();
    assert.equal(await chip.getAttribute('aria-busy'), null);
    await chip.click();
    await page.locator('.cr-packs.ui-loading-surface').waitFor();
    assert.equal(await page.locator('.cr-pack').count(), payload.packs.length);
    await respond(payload);
    await page.locator('.cr-packs:not(.ui-loading-surface)').waitFor();
    assert.equal(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth), true, 'wallet has no horizontal overflow');
    await shot('credits');
    await sheet.evaluate(el => { el.scrollTop = el.scrollHeight; });
    const description = await page.locator('.cr-uses li').last().boundingBox();
    const footer = await page.locator('.cr-checkout').boundingBox();
    assert.ok(description.y + description.height <= footer.y, 'feature details remain readable above the checkout footer');
    await shot('credits-scrolled');
    await sheet.evaluate(el => { el.scrollTop = 0; });
    const last = page.locator('.cr-pack').last();
    await last.click();
    assert.equal(await last.getAttribute('aria-checked'), 'true');
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.locator('.cr-pack').first().getAttribute('aria-checked'), 'true', 'keyboard selection wraps to the first pack');
    assert.equal(await page.locator('.cr-pack').first().evaluate(el => el.matches(':focus')), true);
    await page.getByRole('tab', { name: 'Activity', exact: true }).click();
    assert.equal(await page.locator('.cr-empty').isVisible(), true);
    payload.history = [{ id: 'entry-1', kind: 'purchase', delta: 100, feature: null, description: 'Starter credits', createdAt: '2026-10-26T09:00:00Z' }];
    await page.evaluate(() => { void review.wallet.client.refresh(); });
    await respond(payload);
    await page.locator('.cr-entry').waitFor();
    assert.equal(await page.locator('.cr-delta').innerText(), '+100');
    await shot('activity');
    await page.getByRole('tab', { name: 'Buy credits', exact: true }).click();
    const buy = page.locator('.cr-buy');
    assert.equal((await buy.boundingBox()).height, 54);
    assert.match(await buy.innerText(), /9,99/);
    await buy.click();
    await page.locator('.cr-buy.ui-loading-surface').waitFor();
    assert.equal(await buy.isDisabled(), true);
    const checkout = await take();
    assert.equal(checkout.request().postDataJSON().pack, payload.packs[0].id, 'checkout uses the selected pack');
    await checkout.fulfill({ status: 503, json: { error: { code: 'CREDITS_UNAVAILABLE' } } });
    await page.locator('.cr-buy:not(.ui-loading-surface)').waitFor();
    assert.equal(await buy.isEnabled(), true);
    await page.locator('.cr-shop .cr-error:not([hidden])').waitFor();
    await buy.click();
    await (await take()).fulfill({ json: { orderId: 'pretend-order', url: 'https://checkout.example.test' } });
    await page.waitForFunction(() => review.redirects.length === 1);
    assert.deepEqual(await page.evaluate(() => review.redirects), ['https://checkout.example.test']);
    await page.evaluate(() => { review.wallet.close(); review.charge = review.wallet.charge('technical-drawings'); });
    await page.locator('.cr-confirm:not([hidden])').waitFor();
    await shot('spend-confirmation');
    await page.locator('.cr-confirm-cancel').click();
    assert.equal(await page.evaluate(() => review.charge), false, 'cancelling a paid use spends nothing');
    assert.equal(requests.length, 0);
    await page.evaluate(() => review.wallet.open({ view: 'wait' }));
    assert.equal(await page.locator('.cr-wait.ui-loading-surface').isVisible(), true);
    assert.equal(await page.locator('.cr-spinner').count(), 0);
    await shot('payment-confirming');
    await page.goto(base + '/credit-loading-review?paid=1');
    const returning = [await take(), await take()];
    const balanceRequest = returning.find(route => route.request().url().endsWith('/api/credits'));
    const orderRequest = returning.find(route => route.request().url().includes('/api/credits/orders/'));
    assert.ok(balanceRequest && orderRequest, 'returning from checkout loads the wallet and confirms the order');
    const paidWallet = { ...payload, balance: 90 };
    await balanceRequest.fulfill({ json: paidWallet });
    await page.getByRole('menuitem', { name: 'Credits: 90. Open your wallet', exact: true }).waitFor();
    await orderRequest.fulfill({ json: { orderId: '00000000-0000-4000-8000-000000000001', status: 'paid', credits: 40, balance: 90 } });
    await respond(paidWallet);
    await page.locator('.cr-done:not([hidden])').waitFor();
    assert.equal(await page.locator('.cr-done-title').innerText(), '+40 credits');
    assert.equal(await page.locator('.cr-done-close').isVisible(), true);
    await shot('payment-complete');
    await page.locator('.cr-done-close').click();
    assert.equal(await sheet.isHidden(), true);
    assert.deepEqual(errors, []);
    await page.close();
    console.log(`PASS credits @${width}px: loading, pack selection, keyboard navigation, activity, checkout failure/retry, spend confirmation and payment completion.`);
  }
} finally { await browser.close(); }
