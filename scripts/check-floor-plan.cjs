const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
 const browser = await chromium.launch({headless:true});
 try {
 for (const width of [390, 1440]) {
  const page = await browser.newPage({ viewport:{width,height:900}, reducedMotion:'reduce', hasTouch:width<600, isMobile:width<600 });
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  const spec={specVersion:1,room:{template:'bedroom'},wardrobes:[]};
  await page.goto((process.env.MOBILE_TEST_URL || 'http://127.0.0.1:5198')+'/#spec='+encodeURIComponent(JSON.stringify(spec)));
  await page.getByRole('button',{name:'2D floor plan',exact:true}).click();
  await page.locator('.floor-plan .plan-wall').first().waitFor();
  const root = page.locator('.floor-plan');
  assert.equal(await root.isVisible(),true);
  assert.ok(await root.locator('.plan-wall').count()>=4);
  const before=await page.evaluate(()=>window.furnidraw.describe());
  const badge=root.locator('.measurement-badge').first(); await badge.click();
  const input=badge.locator('input'); await input.waitFor();
  const value=Number(await input.inputValue()); await input.fill(String(value+10)); await input.press('Enter');
  await page.waitForTimeout(250);
  const changed=await page.evaluate(()=>window.furnidraw.describe()); assert.notDeepEqual(changed,before);
  await page.keyboard.press('ControlOrMeta+z'); await page.waitForTimeout(250);
  assert.deepEqual(await page.evaluate(()=>window.furnidraw.describe()),before);
  await page.keyboard.press('ControlOrMeta+Shift+z'); await page.waitForTimeout(250);
  assert.deepEqual(await page.evaluate(()=>window.furnidraw.describe()),changed);
  await page.getByRole('button',{name:'Return to 3D',exact:true}).click();
  assert.equal(await root.isVisible(),false);
  assert.deepEqual(await page.evaluate(()=>window.furnidraw.describe()),changed);
  await page.getByRole('button',{name:'2D floor plan',exact:true}).click();
  const report=()=>page.evaluate(()=>window.furnidraw.describe());
  const baseline=await report();
  await root.locator('[data-action="door"]').click();
  const line=root.locator('[data-kind="wall"] .plan-hit').first();
  const svgBox=await root.locator('svg').boundingBox();
  const at=await line.evaluate(e=>({x:(+e.getAttribute('x1')+ +e.getAttribute('x2'))/2,y:(+e.getAttribute('y1')+ +e.getAttribute('y2'))/2}));
  await page.mouse.click(svgBox.x+at.x,svgBox.y+at.y);
  await root.locator('[data-opening][data-field="width"]').waitFor({timeout:3000});
  assert.notDeepEqual(await report(),baseline,'place hosted door');
  await root.locator('[data-action="swing"]').click();
  assert.ok(await root.locator('[data-action="swing"]').isVisible(),'door operation stays selected');
  const field=root.locator('[data-opening][data-field="width"]');await field.click();
  const entry=field.locator('input');await entry.fill('90');await entry.press('Enter');
  const resized=await report();
  await page.keyboard.press('ControlOrMeta+z');await page.waitForTimeout(100);assert.notDeepEqual(await report(),resized);
  await page.keyboard.press('ControlOrMeta+Shift+z');await page.waitForTimeout(100);assert.deepEqual(await report(),resized);
  const corner=root.locator('[data-kind="corner"]').first(), box=await corner.boundingBox();
  const beforeDrag=await report();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  await page.mouse.move(box.x+box.width/2-20,box.y+box.height/2-15,{steps:6});await page.mouse.up();
  assert.notDeepEqual(await report(),beforeDrag,'drag connected corner');
  await page.keyboard.press('ControlOrMeta+z');await page.waitForTimeout(150);assert.deepEqual(await report(),beforeDrag);
  await root.locator('[data-action="draw"]').click();
  const wallCount=await root.locator('.plan-wall').count();
  await page.mouse.click(svgBox.x+80,svgBox.y+170);await page.mouse.click(svgBox.x+280,svgBox.y+170);
  assert.equal(await root.locator('.plan-wall').count(),wallCount+1,'draw a wall');
  await page.keyboard.press('Escape');
  await page.keyboard.press('ControlOrMeta+z');await page.waitForTimeout(150);
  assert.equal(await root.locator('.plan-wall').count(),wallCount);
  await page.screenshot({path:`/private/tmp/floor-plan-${width}.png`});
  await page.evaluate(()=>window.furnidraw.build({specVersion:1,room:{width:500,depth:400},wardrobes:[{against:1,width:120,for:{shoes:8}}]}));
  await root.locator('[data-action="fit"]').click();
  const beforeFurniture=await report();
  const cabinet=root.locator('[data-kind="cabinet"] .plan-cabinet').first();
  const cabinetBox=await cabinet.boundingBox(), px=cabinetBox.x+cabinetBox.width/2, py=cabinetBox.y+cabinetBox.height/2;
  await page.mouse.move(px,py);await page.mouse.down();await page.mouse.move(px,py+70,{steps:8});await page.mouse.up();
  const movedFurniture=await report();assert.notDeepEqual(movedFurniture,beforeFurniture,'move furniture');
  assert.deepEqual(movedFurniture.wardrobes[0].sections,beforeFurniture.wardrobes[0].sections,'preserve all fittings');
  assert.deepEqual(movedFurniture.wardrobes[0].holds,beforeFurniture.wardrobes[0].holds,'preserve configuration');
  await page.keyboard.press('ControlOrMeta+z');await page.waitForTimeout(150);assert.deepEqual(await report(),beforeFurniture);
  await page.keyboard.press('ControlOrMeta+Shift+z');await page.waitForTimeout(150);assert.deepEqual(await report(),movedFurniture);
  await page.mouse.move(px,py+70);await page.mouse.down();await page.mouse.move(px,py+3,{steps:8});await page.mouse.up();
  assert.equal((await report()).wardrobes[0].against,1,'snap furniture flush to wall');
  assert.match(await root.locator('.floor-plan-status').textContent(),/Flush/);
  const beforeCancel=await report();
  await page.mouse.move(px,py);await page.mouse.down();await page.mouse.move(px+20,py+50,{steps:5});await page.keyboard.press('Escape');await page.mouse.up();
  assert.deepEqual(await report(),beforeCancel,'cancel drag restores scene');
  if(width<600){
   const session=await page.context().newCDPSession(page);
   const initialWidth=await root.locator('[data-kind="wall"] .plan-hit').first().evaluate(e=>Math.abs(+e.getAttribute('x2')- +e.getAttribute('x1')));
   await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:120,y:200,id:1},{x:240,y:200,id:2}]});
   await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:90,y:200,id:1},{x:270,y:200,id:2}]});
   await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
   const zoomedWidth=await root.locator('[data-kind="wall"] .plan-hit').first().evaluate(e=>Math.abs(+e.getAttribute('x2')- +e.getAttribute('x1')));
   assert.ok(zoomedWidth>initialWidth*1.2,'two-finger pinch zooms the plan');
   assert.deepEqual(await report(),beforeCancel,'pinch never edits the scene');
   await session.detach();
  }
  assert.deepEqual(errors,[]); console.log(`PASS ${width}px: walls, openings, furniture snapping, cancellation, undo/redo and 3D continuity`);
  await page.close();
 }
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
