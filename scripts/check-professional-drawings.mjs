// Vite on port 5177. All fixtures are local, isolated from saved projects.
import assert from 'node:assert/strict';
import { writeFile, mkdir, unlink } from 'node:fs/promises';
import { chromium } from 'playwright';
import { drawingFixture } from './professional-drawing-fixtures.mjs';
const output = 'docs/verification/professional-drawings'; await mkdir(output, { recursive: true });
const fixture = '.professional-drawings-review.html', scene = drawingFixture('l');
await writeFile(fixture, `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body style="margin:0">
<main id="fixture" style="height:100dvh;width:100%"></main><script type="module">
import { mountEditor } from '/src/presentation/editor/mount-editor.ts';
window.fixtureEditor=mountEditor({root:document.querySelector('#fixture'),initialScene:${JSON.stringify(scene)}});
</script></body></html>`);
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5177/' + fixture);
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Technical drawings', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Technical drawings', exact: true });
  await dialog.locator('.drawings-sheet img').waitFor();
  assert.ok(await dialog.getByRole('button', { name: /^Cabinet K/ }).count() > 0);
  await page.screenshot({ path: output + '/desktop-layout.png' });
  await dialog.getByRole('button', { name: 'Installation', exact: true }).click();
  await page.screenshot({ path: output + '/desktop-installation.png' });
  await dialog.getByRole('button', { name: 'Clearances', exact: true }).click();
  await dialog.getByRole('button', { name: /^Checks/ }).click();
  await page.screenshot({ path: output + '/desktop-clearances.png' });
  await dialog.locator('[data-issue]').first().click();
  await dialog.locator('.drawing-location').waitFor();
  await dialog.getByRole('combobox', { name: 'Clearance review profile' }).selectOption('nkba-multiple');
  assert.match(await dialog.locator('.drawing-rule').innerText(), /multiple cooks/);
  await dialog.getByRole('button', { name: 'Close drawing details', exact: true }).click();
  await dialog.getByRole('button', { name: 'Layout', exact: true }).click();
  await dialog.getByRole('button', { name: 'Cabinet K1', exact: true }).click();
  await dialog.getByRole('button', { name: 'Move label right', exact: true }).click();
  assert.match(await dialog.locator('.drawing-status').innerText(), /saved|nearest clear/);
  const stored = await page.evaluate(() => Object.entries(localStorage).filter(([key]) => key.includes('drawing')));
  assert.ok(stored.length > 0, 'label offsets persisted');
  await page.screenshot({ path: output + '/desktop-cabinet.png' });
  await dialog.getByRole('button', { name: 'Open cabinet details', exact: true }).click();
  assert.match(await dialog.locator('.drawing-current').innerText(), /K1/);
  await dialog.getByRole('button', { name: 'Layout', exact: true }).click();
  await dialog.getByRole('button', { name: 'Sheets', exact: true }).click();
  await dialog.getByRole('searchbox', { name: 'Search sheets', exact: true }).fill('Upper');
  await dialog.locator('.drawing-index-list button').click();
  assert.match(await dialog.locator('.drawing-current').innerText(), /Upper/);
  await dialog.getByRole('button', { name: 'Save as PDF', exact: true }).click();
  const preview = dialog.getByRole('dialog', { name: 'Export preview', exact: true }); await preview.waitFor();
  const download = page.waitForEvent('download'); await preview.getByRole('button', { name: 'Download PDF', exact: true }).click();
  await (await download).saveAs(output + '/layout.pdf');
  await page.setViewportSize({ width: 375, height: 812 });
  await dialog.getByRole('button', { name: 'Close drawing details', exact: true }).click();
  await dialog.getByRole('button', { name: 'Fit drawing', exact: true }).click();
  await page.screenshot({ path: output + '/mobile-upper.png' });
  await dialog.getByRole('button', { name: 'Previous sheet', exact: true }).click();
  await dialog.getByRole('button', { name: 'Fit drawing', exact: true }).click();
  await page.screenshot({ path: output + '/mobile-layout.png' });
  await dialog.getByRole('button', { name: 'Cabinets', exact: true }).click();
  await page.screenshot({ path: output + '/mobile-cabinets.png' });
  await dialog.getByRole('button', { name: 'Close drawing details', exact: true }).click();
  await dialog.getByRole('button', { name: 'Zoom in', exact: true }).click();
  await dialog.getByRole('button', { name: 'Fit page', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await dialog.getByRole('button', { name: 'Close technical drawings', exact: true }).click(); await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Technical drawings', exact: true }).click();
  assert.deepEqual(await page.evaluate(() => Object.entries(localStorage).filter(([key]) => key.includes('drawing'))), stored);
  await dialog.getByRole('button', { name: 'Close technical drawings', exact: true }).click();
  const touchPage = await browser.newPage({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true });
  touchPage.on('pageerror', e => errors.push(e.message)); await touchPage.goto('http://127.0.0.1:5177/' + fixture);
  await touchPage.getByRole('button', { name: 'Menu', exact: true }).tap();
  await touchPage.getByRole('menuitem', { name: 'Technical drawings', exact: true }).tap();
  const touchDialog = touchPage.getByRole('dialog', { name: 'Technical drawings', exact: true });
  const stage = touchDialog.locator('.drawings-sheets'), before = await touchDialog.locator('.drawings-sheet').boundingBox(), frame = await stage.boundingBox();
  const client = await touchPage.context().newCDPSession(touchPage), cy = frame.y + frame.height / 2;
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 140, y: cy, id: 1 }, { x: 230, y: cy, id: 2 }] });
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 90, y: cy, id: 1 }, { x: 280, y: cy, id: 2 }] });
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.ok((await touchDialog.locator('.drawings-sheet').boundingBox()).width > before.width * 1.8, 'two-finger pinch changes drawing zoom');
  await touchDialog.getByRole('button', { name: 'Fit drawing', exact: true }).tap();
  await touchDialog.getByRole('button', { name: 'Cabinet K1', exact: true }).tap();
  await touchPage.screenshot({ path: output + '/mobile-touch.png' });
  await touchDialog.getByRole('button', { name: 'Close technical drawings', exact: true }).tap();
  assert.deepEqual(errors, []);
  console.log('Dense L-plan: purposes, tags, saved positioning, cabinet details, upper plan, export preview/download and 375px navigation passed.');
} finally { await browser?.close(); await unlink(fixture); }
